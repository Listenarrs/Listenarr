namespace Listenarr.Tests.Common
{
    /// <summary>
    /// Records each rendered log line together with the exception that came with it, so a test
    /// can assert on everything a real sink would write (message text and exception text).
    /// </summary>
    public sealed class RecordingLogger : ILogger
    {
        public List<(LogLevel Level, string Message, Exception? Exception)> Entries { get; } = [];

        public IDisposable? BeginScope<TState>(TState state)
            where TState : notnull => null;

        public bool IsEnabled(LogLevel logLevel) => true;

        public void Log<TState>(
            LogLevel logLevel,
            EventId eventId,
            TState state,
            Exception? exception,
            Func<TState, Exception?, string> formatter)
        {
            Entries.Add((logLevel, formatter(state, exception), exception));
        }

        // What a console or file sink would emit: the rendered message plus the full exception text.
        public string AllOutput() => string.Join(
            "\n",
            Entries.Select(e => e.Exception is null ? e.Message : e.Message + "\n" + e.Exception));
    }
}
